use std::collections::HashMap;
use std::fmt::Write;
use std::path::Path;

use crate::sas::Model;

/// How the search is bounded.
#[derive(Clone, Debug)]
pub struct Options {
    /// With no `schedule`, the number of iterative-deepening rounds: bounds 1, 2, 4, ...
    pub rounds: usize,
    /// With no `schedule`, bounds 1, 2, 3, ... rather than 1, 2, 4, ...
    pub linear: bool,
    /// Every abstract task spends a level of the bound, not only those on a cycle.
    pub count_all: bool,
    /// The bounds to try, overriding `rounds` and `linear`.
    pub schedule: Option<Vec<u64>>,
    /// Test inferred preconditions before searching a task or the rest of a method.
    pub prune: bool,
    /// Cache a compound task's stream under the state restricted to the facts it can touch.
    pub project: bool,
}

impl Default for Options {
    /// Bounds 64, 256, 1024. A generous first bound lets depth-first search dive straight down a
    /// plan instead of exhausting every shallow round first, and the cache makes a bound larger
    /// than needed cheap; on the IPC 2023 total-order set this needs about half the work of
    /// deepening from 1.
    fn default() -> Options {
        Options {
            rounds: 10,
            linear: false,
            count_all: false,
            schedule: Some(vec![64, 256, 1024]),
            prune: true,
            project: true,
        }
    }
}

impl Options {
    /// The depth bounds iterative deepening tries, in order.
    pub fn bounds(&self) -> Vec<u64> {
        match &self.schedule {
            Some(bounds) => bounds.clone(),
            None => (0..self.rounds)
                .map(|k| if self.linear { k as u64 + 1 } else { 1u64 << k.min(62) })
                .collect(),
        }
    }
}

/// Writes the grounded model out as the type-level program `src/problem.rs`, which the `weave`
/// binary includes. `source` is the `.sas` file, which `weave` reads back at run time for the
/// names it prints; the compiled-in program carries nothing but what the search needs.
pub fn generate(model: &Model, source: &str, options: &Options) -> Result<String, String> {
    if !model.is_htn {
        return Err("not an HTN problem".into());
    }
    if !model.is_totally_ordered {
        return Err("twine plans totally ordered problems only".into());
    }
    if model.has_conditional_effects {
        return Err("conditional effects are not encoded".into());
    }

    let bits = model.num_state_bits;
    let kinds = if options.count_all { vec!["Comp"; model.num_tasks] } else { kinds(model) };
    let order = method_order(model);
    let mut masks = Masks::new(bits);
    let inferred = crate::infer::infer(model);
    let touched = crate::infer::touched(model);
    let mut s = String::new();
    let name = Path::new(source).file_name().map_or(source.into(), |n| n.to_string_lossy());
    writeln!(s, "//! Generated by `cargo weave-gen` from {name}. Do not edit.").unwrap();
    writeln!(s, "//!").unwrap();
    writeln!(
        s,
        "//! {bits} state bits, {} actions, {} tasks, {} methods.",
        model.num_actions,
        model.num_tasks,
        model.methods.len()
    )
    .unwrap();
    writeln!(s).unwrap();
    writeln!(s, "#![allow(clippy::all, dead_code)]").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "use twine::bit::{{B0, B1}};").unwrap();
    writeln!(s, "use twine::list::{{Cons, Nil}};").unwrap();
    writeln!(s, "use twine::search::Problem;").unwrap();
    writeln!(s, "use twine::state::{{Br, Off, On}};").unwrap();
    writeln!(s, "use twine::search::{{Alt, Alts, Fin}};").unwrap();
    writeln!(s, "use twine::task::{{Comp, Flat, Guard, Id, Pass, Prim, Proj, Sub, Task}};")
        .unwrap();
    writeln!(s).unwrap();
    writeln!(s, "/// The grounded model, read back at run time for names and to check the plan.")
        .unwrap();
    writeln!(s, "pub const SOURCE: &str = {source:?};").unwrap();
    writeln!(s).unwrap();

    for task in 0..model.num_tasks {
        writeln!(s, "// {}", model.task_names[task]).unwrap();
        let kind = if task < model.num_actions {
            let action = &model.actions[task];
            format!(
                "Prim<Id<{task}>, {}, {}, {}>",
                masks.mask(&action.prec),
                masks.mask(&action.add),
                masks.mask(&action.del)
            )
        } else {
            // One marker per method, each naming the next to try.
            let methods = &order[task];
            for (k, &m) in methods.iter().enumerate() {
                let tails = &inferred.tails[m as usize];
                let subtasks: Vec<String> = model.methods[m as usize]
                    .subtasks
                    .iter()
                    .enumerate()
                    .map(|(i, t)| {
                        let pre = if options.prune { masks.mask(&tails[i]) } else { "Off".into() };
                        format!("Sub<T{t}, {pre}>")
                    })
                    .collect();
                let subtasks = subtasks.into_iter();
                let next = methods.get(k + 1).map_or("Fin".to_string(), |n| format!("A{n}"));
                writeln!(s, "pub struct A{m};").unwrap();
                writeln!(
                    s,
                    "impl Alts for A{m} {{\n    type Cell = Alt<Id<{m}>, {}, {next}>;\n}}",
                    list(subtasks)
                )
                .unwrap();
            }
            let first = methods.first().map_or("Fin".to_string(), |m| format!("A{m}"));
            let mut kind = format!("{}<{first}>", kinds[task]);
            if options.prune && !inferred.task[task].is_empty() {
                kind = format!("Guard<{}, {kind}>", masks.mask(&inferred.task[task]));
            }
            if options.project && touched[task].len() < bits {
                kind = format!("Proj<{}, {kind}>", masks.mask(&touched[task]));
            }
            kind
        };
        writeln!(s, "pub struct T{task};").unwrap();
        writeln!(s, "impl Task for T{task} {{\n    type Kind = {kind};\n}}").unwrap();
    }
    writeln!(s).unwrap();

    writeln!(s, "pub struct Prob;").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "impl Problem for Prob {{").unwrap();
    writeln!(s, "    type Init = {};", masks.mask(&model.s0)).unwrap();
    writeln!(s, "    type Goal = {};", masks.mask(&model.goal)).unwrap();
    writeln!(s, "    type Root = T{};", model.initial_task).unwrap();
    writeln!(s, "    type Schedule = {};", list(options.bounds().into_iter().map(binary))).unwrap();
    writeln!(s, "}}").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "// Every interior node of every mask, once.").unwrap();
    s.push_str(&masks.defs);

    Ok(s)
}

/// A type-level list, spelled out: a macro would cost an expansion step per element.
fn list(items: impl Iterator<Item = String>) -> String {
    let mut out = String::new();
    let mut n = 0;
    for item in items {
        out.push_str("Cons<");
        out.push_str(&item);
        out.push_str(", ");
        n += 1;
    }
    out.push_str("Nil");
    out.push_str(&">".repeat(n));
    out
}

/// Builds masks, sharing them: every interior node of every trie is named once, as a type
/// alias, and a mask is the name of its root. The masks of a grounded model repeat the same
/// sparse paths thousands of times over, and spelling each one out is most of what rustc would
/// otherwise have to parse.
struct Masks {
    height: usize,
    names: HashMap<(String, String), String>,
    defs: String,
}

impl Masks {
    fn new(bits: usize) -> Masks {
        let mut height = 0;
        while (1usize << height) < bits {
            height += 1;
        }
        Masks { height, names: HashMap::new(), defs: String::new() }
    }

    /// The canonical trie, padded to a power of two, that has exactly `facts` set.
    fn mask(&mut self, facts: &[u32]) -> String {
        let mut sorted = facts.to_vec();
        sorted.sort_unstable();
        sorted.dedup();
        self.trie(&sorted, 0, self.height)
    }

    fn trie(&mut self, facts: &[u32], lo: usize, height: usize) -> String {
        if facts.is_empty() {
            return "Off".into();
        }
        if height == 0 {
            return "On".into();
        }
        let mid = lo + (1 << (height - 1));
        let split = facts.partition_point(|&f| (f as usize) < mid);
        let l = self.trie(&facts[..split], lo, height - 1);
        let r = self.trie(&facts[split..], mid, height - 1);
        let next = self.names.len();
        let defs = &mut self.defs;
        self.names
            .entry((l, r))
            .or_insert_with_key(|(l, r)| {
                writeln!(defs, "type K{next} = Br<{l}, {r}>;").unwrap();
                format!("K{next}")
            })
            .clone()
    }
}

/// A binary numeral, least significant bit first, with no trailing `B0`.
fn binary(mut n: u64) -> String {
    let mut bits = Vec::new();
    while n > 0 {
        bits.push(if n & 1 == 1 { "B1".to_string() } else { "B0".to_string() });
        n >>= 1;
    }
    list(bits.into_iter())
}

/// How each abstract task treats the depth bound: `Comp` if it is on a cycle of the
/// decomposition graph, `Pass` if it can reach one, `Flat` if it cannot.
pub fn kinds(model: &Model) -> Vec<&'static str> {
    let n = model.num_tasks;
    let mut edges: Vec<Vec<usize>> = vec![Vec::new(); n];
    for method in &model.methods {
        for &sub in &method.subtasks {
            edges[method.task as usize].push(sub as usize);
        }
    }
    for e in &mut edges {
        e.sort_unstable();
        e.dedup();
    }

    // Tarjan, iteratively. Components come out in reverse topological order, so everything a
    // component can reach has already been classified when it is.
    let mut index = vec![usize::MAX; n];
    let mut low = vec![0; n];
    let mut on_stack = vec![false; n];
    let mut stack = Vec::new();
    let mut kind = vec![""; n];
    let mut reaches_cycle = vec![false; n];
    let mut next = 0;
    for start in 0..n {
        if index[start] != usize::MAX {
            continue;
        }
        let mut frames = vec![(start, 0usize)];
        index[start] = next;
        low[start] = next;
        next += 1;
        stack.push(start);
        on_stack[start] = true;
        while let Some(&mut (v, ref mut i)) = frames.last_mut() {
            if *i < edges[v].len() {
                let w = edges[v][*i];
                *i += 1;
                if index[w] == usize::MAX {
                    index[w] = next;
                    low[w] = next;
                    next += 1;
                    stack.push(w);
                    on_stack[w] = true;
                    frames.push((w, 0));
                } else if on_stack[w] {
                    low[v] = low[v].min(index[w]);
                }
                continue;
            }
            frames.pop();
            if let Some(&(parent, _)) = frames.last() {
                low[parent] = low[parent].min(low[v]);
            }
            if low[v] != index[v] {
                continue;
            }
            let mut component = Vec::new();
            loop {
                let w = stack.pop().unwrap();
                on_stack[w] = false;
                component.push(w);
                if w == v {
                    break;
                }
            }
            let cyclic = component.len() > 1 || edges[v].contains(&v);
            let below = component
                .iter()
                .flat_map(|&u| edges[u].iter())
                .any(|&w| !component.contains(&w) && reaches_cycle[w]);
            for &u in &component {
                reaches_cycle[u] = cyclic || below;
                kind[u] = if cyclic {
                    "Comp"
                } else if below {
                    "Pass"
                } else {
                    "Flat"
                };
            }
        }
    }
    kind
}

/// Each abstract task's methods in the order the search should try them: cheapest first, by the
/// fewest actions any decomposition of the method's subtasks can bottom out in. Methods that
/// cannot bottom out at all are dropped. This is the only heuristic, and it is all static: on
/// a recursive task it tries the way out before the way further in.
pub fn method_order(model: &Model) -> Vec<Vec<u32>> {
    const NONE: u64 = u64::MAX;
    let mut cost: Vec<u64> =
        (0..model.num_tasks).map(|t| if t < model.num_actions { 1 } else { NONE }).collect();
    let method_cost = |cost: &[u64], m: usize| {
        model.methods[m].subtasks.iter().try_fold(0u64, |sum, &t| match cost[t as usize] {
            NONE => None,
            c => Some(sum.saturating_add(c)),
        })
    };
    // Bellman-Ford: costs only fall, and each pass settles at least one more task.
    loop {
        let mut changed = false;
        for m in 0..model.methods.len() {
            if let Some(c) = method_cost(&cost, m) {
                let task = model.methods[m].task as usize;
                if c < cost[task] {
                    cost[task] = c;
                    changed = true;
                }
            }
        }
        if !changed {
            break;
        }
    }
    model
        .methods_for
        .iter()
        .map(|methods| {
            let mut scored: Vec<(u64, u32)> = methods
                .iter()
                .filter_map(|&m| method_cost(&cost, m as usize).map(|c| (c, m)))
                .collect();
            scored.sort_by_key(|&(c, _)| c);
            scored.into_iter().map(|(_, m)| m).collect()
        })
        .collect()
}
