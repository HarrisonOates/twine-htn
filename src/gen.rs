use std::fmt::Write;

use crate::sas::Model;

/// Writes the grounded model out as the type-level program `src/problem.rs`.
pub fn generate(model: &Model, source: &str, depth: usize) -> Result<String, String> {
    if !model.is_htn {
        return Err("not an HTN problem".into());
    }
    if !model.is_totally_ordered {
        return Err("twine plans totally ordered problems only".into());
    }
    if model.has_conditional_effects {
        return Err("conditional effects are not encoded".into());
    }

    let bits = model.num_state_bits;
    let num_methods = model.methods.len();
    let mut s = String::new();
    writeln!(s, "//! Generated by `cargo weave-gen` from {source}. Do not edit.").unwrap();
    writeln!(s, "//!").unwrap();
    writeln!(
        s,
        "//! {bits} state bits, {} actions, {} tasks, {num_methods} methods.",
        model.num_actions, model.num_tasks
    )
    .unwrap();
    writeln!(s).unwrap();
    writeln!(s, "#![allow(clippy::all)]").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "use crate::bit::{{Succ, Zero, B0, B1}};").unwrap();
    writeln!(s, "use crate::domain::{{ActionInfo, Domain, MethodInfo}};").unwrap();
    writeln!(s, "use crate::search::Problem;").unwrap();
    writeln!(s, "use crate::task::{{Action, Comp, Ident, Method, Prim, Task}};").unwrap();
    writeln!(s, "use crate::tlist;").unwrap();
    writeln!(s).unwrap();

    for task in 0..model.num_tasks {
        writeln!(s, "/// {}", model.task_names[task]).unwrap();
        writeln!(s, "pub struct T{task};").unwrap();
        writeln!(s, "impl Ident for T{task} {{\n    const ID: u32 = {task};\n}}").unwrap();
        if task < model.num_actions {
            let action = &model.actions[task];
            writeln!(s, "impl Task for T{task} {{\n    type Kind = Prim<T{task}>;\n}}").unwrap();
            writeln!(s, "impl Action for T{task} {{").unwrap();
            writeln!(s, "    type Prec = {};", mask(&action.prec, bits)).unwrap();
            writeln!(s, "    type Add = {};", mask(&action.add, bits)).unwrap();
            writeln!(s, "    type Del = {};", mask(&action.del, bits)).unwrap();
            writeln!(s, "}}").unwrap();
        } else {
            let methods: Vec<String> =
                model.methods_for[task].iter().map(|m| format!("M{m}")).collect();
            writeln!(
                s,
                "impl Task for T{task} {{\n    type Kind = Comp<tlist![{}]>;\n}}",
                methods.join(", ")
            )
            .unwrap();
        }
        writeln!(s).unwrap();
    }

    for (method, info) in model.methods.iter().enumerate() {
        let names: Vec<String> = info.subtasks.iter().map(|t| format!("T{t}")).collect();
        writeln!(s, "/// {}", info.name).unwrap();
        writeln!(s, "pub struct M{method};").unwrap();
        writeln!(s, "impl Ident for M{method} {{\n    const ID: u32 = {method};\n}}").unwrap();
        writeln!(
            s,
            "impl Method for M{method} {{\n    type Subtasks = tlist![{}];\n}}",
            names.join(", ")
        )
        .unwrap();
        writeln!(s).unwrap();
    }

    writeln!(s, "pub struct Prob;").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "impl Problem for Prob {{").unwrap();
    writeln!(s, "    type Init = {};", mask(&model.s0, bits)).unwrap();
    writeln!(s, "    type Goal = {};", mask(&model.goal, bits)).unwrap();
    writeln!(s, "    type Root = T{};", model.initial_task).unwrap();
    writeln!(s, "    type MaxDepth = {};", peano(depth)).unwrap();
    writeln!(s, "}}").unwrap();
    writeln!(s).unwrap();

    writeln!(s, "impl Domain for Prob {{").unwrap();
    writeln!(s, "    const NUM_FACTS: usize = {bits};").unwrap();
    writeln!(s, "    const ROOT: u32 = {};", model.initial_task).unwrap();
    writeln!(s, "    const INIT: &'static [u32] = &{:?};", model.s0).unwrap();
    writeln!(s, "    const GOAL: &'static [u32] = &{:?};", model.goal).unwrap();
    writeln!(s, "    const FACTS: &'static [&'static str] = &[").unwrap();
    for fact in &model.fact_names {
        writeln!(s, "        {fact:?},").unwrap();
    }
    writeln!(s, "    ];").unwrap();
    writeln!(s, "    const TASKS: &'static [&'static str] = &[").unwrap();
    for name in &model.task_names {
        writeln!(s, "        {name:?},").unwrap();
    }
    writeln!(s, "    ];").unwrap();
    writeln!(s, "    const ACTIONS: &'static [ActionInfo] = &[").unwrap();
    for (action, info) in model.actions.iter().enumerate() {
        writeln!(
            s,
            "        ActionInfo {{ name: {:?}, prec: &{:?}, add: &{:?}, del: &{:?} }},",
            model.task_names[action], info.prec, info.add, info.del
        )
        .unwrap();
    }
    writeln!(s, "    ];").unwrap();
    writeln!(s, "    const METHODS: &'static [MethodInfo] = &[").unwrap();
    for info in &model.methods {
        writeln!(
            s,
            "        MethodInfo {{ name: {:?}, task: {}, subtasks: &{:?} }},",
            info.name, info.task, info.subtasks
        )
        .unwrap();
    }
    writeln!(s, "    ];").unwrap();
    writeln!(s, "}}").unwrap();

    Ok(s)
}

fn mask(facts: &[u32], bits: usize) -> String {
    let mut set = vec![false; bits];
    for &fact in facts {
        set[fact as usize] = true;
    }
    let cells: Vec<&str> = set.iter().map(|&b| if b { "B1" } else { "B0" }).collect();
    format!("tlist![{}]", cells.join(", "))
}

fn peano(n: usize) -> String {
    format!("{}Zero{}", "Succ<".repeat(n), ">".repeat(n))
}
